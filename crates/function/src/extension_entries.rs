//! The entries of DuckDB's `duckdb/main/extension_entries.hpp`: which extension provides a
//! function, setting, type, copy function or collation that is not in the catalog.

/// The catalog type of an extension function (the `CatalogType` of `ExtensionFunctionEntry`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExtensionFunctionType {
    Scalar,
    Aggregate,
    Table,
    Pragma,
    Macro,
    TableMacro,
}

impl ExtensionFunctionType {
    /// `CatalogTypeToString`.
    pub const fn display_name(self) -> &'static str {
        match self {
            Self::Scalar => "Scalar Function",
            Self::Aggregate => "Aggregate Function",
            Self::Table => "Table Function",
            Self::Pragma => "Pragma Function",
            Self::Macro => "Macro Function",
            Self::TableMacro => "Table Macro Function",
        }
    }
}

