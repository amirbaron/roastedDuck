#!/usr/bin/env python3
"""Extract bison's LALR tables and the keyword list into Rust source.

Reads DuckDB's generated grammar (`src_backend_parser_gram.cpp`, produced by
bison 2.3 from `third_party/libpg_query/grammar`) and the keyword list
(`include/parser/kwlist.hpp`) and writes:

* `src/tables.rs`   -- the parse tables, token codes and symbol names
* `src/keywords.rs` -- the keyword list with a hash lookup table

Usage:
    python3 crates/pg-parser/scripts/extract_tables.py <duckdb-source-root>

Both outputs are checked in; the crate never needs bison at build time.
Regenerate them whenever DuckDB's grammar changes (see the crate README).
"""

from __future__ import annotations

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
CRATE = HERE.parent

# Tables copied verbatim from the bison skeleton, in the order they appear there.
TABLES = [
    # name, rust type, cfg(test) only
    ("yytranslate", "u16", False),
    ("yyprhs", "u16", True),
    ("yyrhs", "i16", True),
    ("yyr1", "u16", False),
    ("yyr2", "u8", False),
    ("yydefact", "u16", False),
    ("yydefgoto", "i16", False),
    ("yypact", "i32", False),
    ("yypgoto", "i32", False),
    ("yytable", "i16", False),
    ("yycheck", "i16", False),
]

CONSTANTS = ["YYFINAL", "YYLAST", "YYNTOKENS", "YYNNTS", "YYNRULES", "YYNSTATES", "YYMAXUTOK",
             "YYPACT_NINF", "YYTABLE_NINF", "YYUNDEFTOK", "YYINITDEPTH", "YYMAXDEPTH"]

RUST_RANGES = {
    "u8": (0, 2**8 - 1),
    "i16": (-(2**15), 2**15 - 1),
    "u16": (0, 2**16 - 1),
    "i32": (-(2**31), 2**31 - 1),
}


def parse_int_array(src: str, name: str) -> list[int]:
    m = re.search(r"static const [\w ]+?\b" + name + r"\[\]\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit(f"table {name} not found")
    return [int(x) for x in re.findall(r"-?\d+", m.group(1))]


def parse_define(src: str, name: str) -> int:
    m = re.search(r"#\s*define\s+" + name + r"\s+\(?(-?\d+)\)?", src)
    if not m:
        raise SystemExit(f"constant {name} not found")
    return int(m.group(1))


def parse_tokens(src: str) -> list[tuple[str, int]]:
    m = re.search(r"enum yytokentype \{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("token enum not found")
    return [(n, int(v)) for n, v in re.findall(r"(\w+) = (\d+)", m.group(1))]


def parse_tname(src: str) -> list[str]:
    m = re.search(r"static const char \*const yytname\[\] =\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("yytname not found")
    names = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
    return [n.replace('\\"', '"').replace("\\\\", "\\") for n in names]


def rust_array(name: str, ty: str, values: list[int], per_line: int = 16) -> str:
    lo, hi = RUST_RANGES[ty]
    bad = [v for v in values if not lo <= v <= hi]
    if bad:
        raise SystemExit(f"{name}: value {bad[0]} does not fit {ty}")
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return f"pub(crate) static {name.upper()}: [{ty}; {len(values)}] = [\n" + "\n".join(lines) + "\n];\n"


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_tables(src: str) -> str:
    out = [
        "//! Bison's LALR(1) tables for DuckDB's Postgres grammar.",
        "//!",
        "//! Generated by `scripts/extract_tables.py` from `src_backend_parser_gram.cpp`",
        "//! (DuckDB 1.5.6, bison 2.3). Do not edit by hand.",
        "",
    ]
    for c in CONSTANTS:
        if c == "YYMAXDEPTH":
            value = 10000  # bison's default; DuckDB does not override it
        else:
            value = parse_define(src, c)
        ty = "i32" if c in ("YYPACT_NINF", "YYTABLE_NINF") else "usize"
        out.append(f"pub(crate) const {c}: {ty} = {value};")
    out.append("")

    tokens = parse_tokens(src)
    out.append("/// Token codes returned by the scanner (bison's `yytokentype`).")
    out.append("///")
    out.append("/// Single-character tokens use their byte value; named tokens start at 258.")
    out.append("#[allow(dead_code)]")
    out.append("pub(crate) mod token {")
    for n, v in tokens:
        out.append(f"    pub(crate) const {n}: u16 = {v};")
    out.append("}")
    out.append("")

    for name, ty, test_only in TABLES:
        values = parse_int_array(src, name)
        if test_only:
            out.append("#[cfg(test)]")
        out.append(rust_array(name, ty, values))

    names = parse_tname(src)
    out.append("/// Grammar symbol names (bison's `yytname`), indexed by symbol number.")
    out.append("#[cfg(test)]")
    out.append(f"pub(crate) static YYTNAME: [&str; {len(names)}] = [")
    for n in names:
        out.append(f"    {rust_str(n)},")
    out.append("];")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------------------
# Keywords
# --------------------------------------------------------------------------------------

CATEGORIES = {
    "UNRESERVED_KEYWORD": "Unreserved",
    "COL_NAME_KEYWORD": "ColName",
    "TYPE_FUNC_NAME_KEYWORD": "TypeFunc",
    "RESERVED_KEYWORD": "Reserved",
}


def keyword_hash(word: bytes, seed: int, mask: int) -> int:
    """Must match `keywords::hash` in Rust (FNV-1a style)."""
    h = seed
    for b in word:
        h = ((h ^ b) * 0x0100_0193) & 0xFFFF_FFFF
    return (h ^ (h >> 15)) & mask


def emit_keywords(kwlist: str, tokens: dict[str, int]) -> str:
    entries = re.findall(r'PG_KEYWORD\("([^"]+)", (\w+), (\w+)\)', kwlist)
    words = [e[0] for e in entries]
    if words != sorted(words):
        raise SystemExit("kwlist.hpp is not sorted")
    # Open addressing with linear probing; the seed is chosen to minimise the longest probe.
    size = 1024
    mask = size - 1
    best = None
    for seed in range(1, 5000):
        table = [0] * size
        longest = 0
        for i, w in enumerate(words):
            h = keyword_hash(w.encode(), seed, mask)
            probes = 1
            while table[h]:
                h = (h + 1) & mask
                probes += 1
            table[h] = i + 1
            longest = max(longest, probes)
        if best is None or longest < best[0]:
            best = (longest, seed, table)
    longest, seed, table = best
    max_len = max(len(w) for w in words)

    out = [
        "//! DuckDB's SQL keyword list (`kwlist.hpp`) and its lookup table.",
        "//!",
        "//! Generated by `scripts/extract_tables.py`. Do not edit by hand.",
        "",
        "use super::{Keyword, KeywordCategory};",
        "use crate::tables::token;",
        "",
        f"pub(super) const HASH_SEED: u32 = {seed};",
        f"pub(super) const HASH_MASK: usize = {mask};",
        f"/// Length of the longest keyword.",
        f"pub(super) const MAX_KEYWORD_LEN: usize = {max_len};",
        "",
        "/// Every keyword, sorted by name (the order `ScanKeywordLookup` searches).",
        f"pub(super) static KEYWORDS: [Keyword; {len(words)}] = [",
    ]
    for name, tok, cat in entries:
        if tok not in tokens:
            raise SystemExit(f"keyword token {tok} missing from grammar")
        out.append(
            f"    Keyword {{ name: {rust_str(name)}, token: token::{tok}, category: KeywordCategory::{CATEGORIES[cat]} }},"
        )
    out.append("];")
    out.append("")
    out.append(f"/// Hash slots (linear probing, at most {longest} probes): index into [`KEYWORDS`] plus one, or zero.")
    out.append(f"pub(super) static SLOTS: [u16; {size}] = [")
    for i in range(0, size, 32):
        out.append("    " + ", ".join(str(v) for v in table[i:i + 32]) + ",")
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    root = pathlib.Path(sys.argv[1])
    pg = root / "third_party" / "libpg_query"
    src = (pg / "src_backend_parser_gram.cpp").read_text()
    kwlist = (pg / "include" / "parser" / "kwlist.hpp").read_text()
    tokens = dict(parse_tokens(src))
    (CRATE / "src" / "tables.rs").write_text(emit_tables(src))
    (CRATE / "src" / "keywords" / "list.rs").write_text(emit_keywords(kwlist, tokens))
    print("wrote src/tables.rs and src/keywords/list.rs")


if __name__ == "__main__":
    main()
