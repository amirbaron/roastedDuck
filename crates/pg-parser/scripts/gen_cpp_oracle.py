def field_dump(cstruct: str, cfield: str, ty: M.Ty) -> str:
    acc = f"s->{cfield}"
    if (cstruct, cfield) in SPECIAL_FIELDS:
        return SPECIAL_FIELDS[(cstruct, cfield)]
    k = ty.kind
    if k in ("node", "box"):
        return f"node((const PGNode *){acc});"
    if k == "list":
        return f"list({acc});"
    if k == "str":
        return f"str({acc});"
    if k == "value":
        return f"value(&{acc});"
    if k == "bool":
        return f"boolean({acc});"
    if k == "u8":
        return f"num((unsigned char){acc});"
    if k in ("int", "u32", "i64", "enum"):
        return f"num((long long){acc});"
    raise KeyError(ty)


def gen(m: M.Model) -> str:
    cases = []
    for cname in M.NODE_STRUCTS:
        rust = M.struct_rust_name(cname)
        lines = [f"\tcase T_{cname}: {{",
                 f"\t\tauto *s = (const {cname} *)n;",
                 f'\t\tout += "{{\\"node\\":\\"{rust}\\"";']
        for cf, rf, ty, _ in gen_nodes.kept_fields(m, cname):
            lines.append(f'\t\tkey("{rf}"); {field_dump(cname, cf, ty)}')
        lines.append('\t\tout += "}";')
        lines.append("\t\treturn;")
        lines.append("\t}")
        cases.append("\n".join(lines))
    fdef = ["static void function_definition(const PGFunctionDefinition *s) {",
            '\tout += "{\\"node\\":\\"FunctionDefinition\\"";']
    for cf, rf, ty, _ in gen_nodes.kept_fields(m, "PGFunctionDefinition"):
        fdef.append(f'\tkey("{rf}"); {field_dump("PGFunctionDefinition", cf, ty)}')
    fdef.append('\tout += "}";')
    fdef.append("}")
    body = MAIN.replace("@@CASES@@", "\n".join(cases))
    body = body.replace("} // namespace oracle", "\n".join(fdef) + "\n\n} // namespace oracle", 1)
    return PRELUDE + body


def main():
    ref = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else M.DEFAULT_REF
    m = M.Model(ref)
    out_dir = M.CRATE.parent.parent / "target" / "pg-oracle"
    out_dir.mkdir(parents=True, exist_ok=True)
    src = out_dir / "pg_oracle.cpp"
    src.write_text(gen(m))
    pg = ref / "third_party" / "libpg_query"
    cmd = [
        "clang++", "-std=c++17", "-O2", "-w",
        f"-I{pg / 'include'}", f"-I{ref / 'src' / 'include'}",
        str(src),
        str(ref / "build" / "release" / "third_party" / "libpg_query" / "libduckdb_pg_query.a"),
        "-o", str(out_dir / "pg_oracle"),
    ]
    subprocess.run(cmd, check=True)
    print(f"built {out_dir / 'pg_oracle'}")


if __name__ == "__main__":
    main()
