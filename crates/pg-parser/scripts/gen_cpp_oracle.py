# Fields whose shape the generic dumper cannot infer from node tags.
SPECIAL_FIELDS = {
    ("PGSelectStmt", "distinctClause"): "distinct_list(s->distinctClause);",
    ("PGCommonTableExpr", "recursive_keys"): "keys_list(s->recursive_keys);",
    ("PGAlterTableCmd", "def_list"): "def_list(s);",
    ("PGRenameStmt", "name_list"): "strings(s->name_list);",
    ("PGAStar", "except_list"): "except_list(s->except_list);",
    ("PGAStar", "rename_list"): "rename_list(s->rename_list);",
    ("PGCreateFunctionStmt", "functions"): "functions(s->functions);",
}

