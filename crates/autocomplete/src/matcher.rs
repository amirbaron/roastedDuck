//! The grammar matcher (DuckDB's `Matcher` hierarchy and `MatcherFactory`,
//! `matcher.cpp`): the PEG grammar compiled into a graph of matchers that consume
//! tokens and, where the tokens run out, collect what could come next.
//!
//! DuckDB allocates the matchers in a `MatcherAllocator` and links them by reference;
//! here they live in one arena ([`Grammar`]) and refer to each other by [`MatcherId`].

use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

use roastedduck_common::{Error, Result};

use crate::keyword_helper::{PegKeywordCategory, PegKeywordHelper};
use crate::peg_parser::{PegParser, PegTokenType};
use crate::tokenizer::{MatcherToken, is_initial_number, is_keyword_character, is_number, is_scientific};
use crate::transformer::parse_result::{ParseResult, ParseResultKind};

/// The grammar DuckDB compiles in (`INLINED_PEG_GRAMMAR`, generated by
/// `inline_grammar.py` from `grammar/statements/*.gram` and `grammar/keywords/*.list`).
const INLINED_PEG_GRAMMAR: &str = include_str!("../grammar/inlined_grammar.gram");

/// The rule the root matcher starts at.
const ROOT_RULE: &str = "Statement";

/// What a suggestion stands for (DuckDB's `SuggestionState`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum SuggestionState {
    Keyword,
    CatalogName,
    SchemaName,
    TableName,
    TypeName,
    ColumnName,
    FileName,
    Directory,
    Variable,
    ScalarFunctionName,
    TableFunctionName,
    PragmaName,
    SettingName,
}

/// How a candidate is written out (DuckDB's `CandidateType`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CandidateType {
    /// Keywords take the case of the typed prefix.
    Keyword,
    /// Identifiers are quoted where needed.
    Identifier,
    /// Literals are written as they are.
    Literal,
}

/// A possible completion before scoring (DuckDB's `AutoCompleteCandidate`).
#[derive(Clone, Debug)]
pub struct AutoCompleteCandidate {
    pub candidate: roastedduck_common::ByteString,
    /// The type being suggested.
    pub suggestion_type: SuggestionState,
    /// The higher the bonus, the better the candidate ranks.
    pub score_bonus: i32,
    pub candidate_type: CandidateType,
    /// A character appended to the suggestion (`'\0'` in DuckDB when there is none).
    pub extra_char: Option<char>,
    /// The byte offset in the query the suggestion replaces from.
    pub suggestion_pos: usize,
    /// The final score.
    pub score: Option<usize>,
}

impl AutoCompleteCandidate {
    pub fn new(
        candidate: impl Into<roastedduck_common::ByteString>,
        suggestion_type: SuggestionState,
        score_bonus: i32,
        candidate_type: CandidateType,
    ) -> Self {
        Self {
            candidate: candidate.into(),
            suggestion_type,
            score_bonus,
            candidate_type,
            extra_char: None,
            suggestion_pos: 0,
            score: None,
        }
    }

    /// An identifier candidate (the defaults of DuckDB's constructor).
    pub fn identifier(
        candidate: impl Into<roastedduck_common::ByteString>,
        suggestion_type: SuggestionState,
        score_bonus: i32,
    ) -> Self {
        Self::new(candidate, suggestion_type, score_bonus, CandidateType::Identifier)
    }
}

/// What the matcher found could come next (DuckDB's `MatcherSuggestion`).
#[derive(Clone, Debug)]
pub enum MatcherSuggestion {
    /// A keyword or symbol of the grammar.
    Keyword(AutoCompleteCandidate),
    /// A name of the given kind, filled in from the catalog, the settings or the file
    /// system.
    Entries(SuggestionState),
}

/// Whether a suggestion must be satisfied before what follows it (DuckDB's
/// `SuggestionType`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum SuggestionType {
    Optional,
    Mandatory,
}

/// The index of a matcher in its [`Grammar`].
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(crate) struct MatcherId(u32);

/// The kinds of matchers (DuckDB's `Matcher` subclasses).
#[derive(Clone, Debug)]
enum MatcherKind {
    /// `KeywordMatcher`: one token, compared case-insensitively.
    Keyword {
        keyword: String,
        score_bonus: i32,
        extra_char: Option<char>,
    },
    /// `ListMatcher`: a sequence.
    List(Vec<MatcherId>),
    /// `OptionalMatcher`.
    Optional(MatcherId),
    /// `ChoiceMatcher`: the first alternative that matches.
    Choice(Vec<MatcherId>),
    /// `RepeatMatcher`: one or more.
    Repeat(MatcherId),
    /// `IdentifierMatcher` (`reserved: false`), which rejects reserved keywords, and
    /// `ReservedIdentifierMatcher` (`reserved: true`), which accepts them.
    Identifier {
        suggestion_type: SuggestionState,
        reserved: bool,
    },
    /// `StringLiteralMatcher`.
    StringLiteral,
    /// `NumberLiteralMatcher`.
    NumberLiteral,
    /// `OperatorMatcher`: multi-character operators of no other rule.
    Operator,
}

#[derive(Clone, Debug)]
struct Matcher {
    kind: MatcherKind,
    /// The name of the rule the matcher was created for, if any.
    name: String,
}

/// The tokens being matched and what matching collected (the shared parts of DuckDB's
/// `MatchState`).
#[derive(Debug)]
pub(crate) struct MatchContext<'t> {
    pub tokens: &'t [MatcherToken],
    pub suggestions: Vec<MatcherSuggestion>,
    /// The furthest token any matcher reached.
    pub max_token_index: usize,
    /// Whether identifiers keep their case in parse results (`preserve_identifier_case`).
    pub preserve_identifier_case: bool,
}

impl<'t> MatchContext<'t> {
    pub fn new(tokens: &'t [MatcherToken]) -> Self {
        Self {
            tokens,
            suggestions: Vec::new(),
            max_token_index: 0,
            preserve_identifier_case: true,
        }
    }
}

/// The position of one matching attempt (the per-copy parts of DuckDB's `MatchState`).
#[derive(Debug, Default)]
pub(crate) struct MatchState {
    pub token_index: usize,
    /// The matchers that added suggestions through this state; DuckDB's copy constructor
    /// starts every child state with an empty set.
    added_suggestions: HashSet<MatcherId>,
}

impl MatchState {
    /// A state at the same position with no suggestions recorded (DuckDB's
    /// `MatchState(MatchState &)`).
    fn child(&self) -> Self {
        Self {
            token_index: self.token_index,
            added_suggestions: HashSet::new(),
        }
    }

    /// Consumes the current token (`token_index++` with `UpdateMaxTokenIndex`).
    fn advance(&mut self, ctx: &mut MatchContext<'_>) {
        self.token_index += 1;
        ctx.max_token_index = ctx.max_token_index.max(self.token_index);
    }
}

/// `IsOperatorChar` of `OperatorMatcher`.
const fn is_operator_char(c: u8) -> bool {
    matches!(
        c,
        b'+' | b'-' | b'*' | b'/' | b'%' | b'^' | b'<' | b'>' | b'=' | b'~' | b'!' | b'@' | b'&' | b'|'
    )
}

/// The prefix of a string literal token (DuckDB's `SpecialStringInfo`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum SpecialStringCharacter {
    Standard,
    NationalString,
    HexadecimalString,
    EscapeString,
    BitString,
}

/// `GetSpecialStringInfo`: the kind of a string literal token and the length of its
/// prefix up to and including the opening quote.
pub(crate) fn special_string_info(text: &str) -> (SpecialStringCharacter, usize) {
    let bytes = text.as_bytes();
    match bytes {
        [] => (SpecialStringCharacter::Standard, 0),
        [prefix, b'\'', ..] if *prefix != b'\'' => {
            let kind = match prefix {
                b'N' | b'n' => SpecialStringCharacter::NationalString,
                b'X' | b'x' => SpecialStringCharacter::HexadecimalString,
                b'B' | b'b' => SpecialStringCharacter::BitString,
                b'E' | b'e' => SpecialStringCharacter::EscapeString,
                _ => return (SpecialStringCharacter::Standard, 1),
            };
            (kind, 2)
        }
        _ => (SpecialStringCharacter::Standard, 1),
    }
}

/// The compiled grammar: every matcher, the root matcher and the keyword categories.
#[derive(Debug)]
pub(crate) struct Grammar {
    matchers: Vec<Matcher>,
    root: MatcherId,
    keywords: PegKeywordHelper,
}

impl Grammar {
    /// The grammar DuckDB compiles in, built on first use (DuckDB builds the matchers
    /// for every call of `Matcher::RootMatcher`; they never change).
    pub fn get() -> Result<&'static Self> {
        static GRAMMAR: OnceLock<std::result::Result<Grammar, Error>> = OnceLock::new();
        GRAMMAR
            .get_or_init(|| Self::build(INLINED_PEG_GRAMMAR, ROOT_RULE))
            .as_ref()
            .map_err(Clone::clone)
    }

    /// `MatcherFactory::CreateMatcher(grammar, root_rule)`.
    fn build(grammar: &'static str, root_rule: &'static str) -> Result<Self> {
        let parser = PegParser::parse_rules(grammar)?;
        let keywords = PegKeywordHelper::from_grammar(&parser)?;
        let mut factory = MatcherFactory::new(&parser);
        let root = factory.create_root(root_rule)?;
        Ok(Self {
            matchers: factory.matchers,
            root,
            keywords,
        })
    }

    fn matcher(&self, id: MatcherId) -> &Matcher {
        &self.matchers[id.0 as usize]
    }

    /// Matches the tokens of `ctx` against the root rule (`Matcher::Match` on
    /// `RootMatcher`), collecting suggestions where they run out.
    pub fn match_root(&self, ctx: &mut MatchContext<'_>, state: &mut MatchState) -> Result<bool> {
        self.matches(self.root, ctx, state)
    }

    /// `Matcher::Match`: whether the matcher matches at the state's position; on success
    /// the state moves past the matched tokens.
    fn matches(&self, id: MatcherId, ctx: &mut MatchContext<'_>, state: &mut MatchState) -> Result<bool> {
        match &self.matcher(id).kind {
            MatcherKind::Keyword { keyword, .. } => {
                let matched = ctx
                    .tokens
                    .get(state.token_index)
                    .is_some_and(|token| token.text.eq_ignore_ascii_case(keyword));
                if matched {
                    state.advance(ctx);
                }
                Ok(matched)
            }
            MatcherKind::List(children) => self.match_list(children, ctx, state),
            MatcherKind::Optional(child) => {
                let mut child_state = state.child();
                if self.matches(*child, ctx, &mut child_state)? {
                    state.token_index = child_state.token_index;
                }
                // Not matching is a success too.
                Ok(true)
            }
            MatcherKind::Choice(children) => {
                for child in children {
                    let mut choice_state = state.child();
                    if self.matches(*child, ctx, &mut choice_state)? {
                        state.token_index = choice_state.token_index;
                        return Ok(true);
                    }
                }
                Ok(false)
            }
            MatcherKind::Repeat(element) => self.match_repeat(*element, ctx, state),
            MatcherKind::Identifier {
                suggestion_type,
                reserved,
            } => {
                let matched = ctx.tokens.get(state.token_index).is_some_and(|token| {
                    (*reserved || self.identifier_allowed(*suggestion_type, &token.text))
                        && is_identifier(*suggestion_type, &token.text)
                });
                if matched {
                    state.advance(ctx);
                }
                Ok(matched)
            }
            MatcherKind::StringLiteral => {
                let matched = ctx
                    .tokens
                    .get(state.token_index)
                    .is_some_and(|token| is_string_literal(&token.text));
                if matched {
                    state.advance(ctx);
                }
                Ok(matched)
            }
            MatcherKind::NumberLiteral => {
                let matched = match ctx.tokens.get(state.token_index) {
                    Some(token) => is_number_literal(&token.text)?,
                    None => false,
                };
                if matched {
                    state.advance(ctx);
                }
                Ok(matched)
            }
            MatcherKind::Operator => {
                let matched = ctx
                    .tokens
                    .get(state.token_index)
                    .is_some_and(|token| is_operator(&token.text));
                if matched {
                    state.advance(ctx);
                }
                Ok(matched)
            }
        }
    }

    /// `ListMatcher::Match`: every child in turn; where the tokens run out, the
    /// suggestions of the remaining children up to the first mandatory one.
    fn match_list(
        &self,
        children: &[MatcherId],
        ctx: &mut MatchContext<'_>,
        state: &mut MatchState,
    ) -> Result<bool> {
        let mut list_state = state.child();
        for (child_index, child) in children.iter().enumerate() {
            if list_state.token_index >= ctx.tokens.len() {
                // The tokens are exhausted: suggest what the remaining children accept.
                let mut index = child_index;
                while index < children.len() {
                    if self.add_suggestion(children[index], ctx, &mut list_state) == SuggestionType::Mandatory
                    {
                        break;
                    }
                    index += 1;
                }
                state.token_index = list_state.token_index;
                // If every remaining child was optional, they all matched.
                return Ok(index == children.len());
            }
            if !self.matches(*child, ctx, &mut list_state)? {
                return Ok(false);
            }
        }
        state.token_index = list_state.token_index;
        Ok(true)
    }

    /// `RepeatMatcher::Match`: the element at least once, then as often as it matches;
    /// where the tokens run out, the element's suggestions.
    fn match_repeat(
        &self,
        element: MatcherId,
        ctx: &mut MatchContext<'_>,
        state: &mut MatchState,
    ) -> Result<bool> {
        let mut repeat_state = state.child();
        if !self.matches(element, ctx, &mut repeat_state)? {
            return Ok(false);
        }
        loop {
            state.token_index = repeat_state.token_index;
            if repeat_state.token_index >= ctx.tokens.len() {
                self.add_suggestion(element, ctx, state);
                return Ok(true);
            }
            if !self.matches(element, ctx, &mut repeat_state)? {
                return Ok(true);
            }
        }
    }

    /// `IdentifierMatcher::MatchIdentifier`'s keyword check: names may not be reserved
    /// keywords, nor keywords of the category banned for the kind of name, unless they
    /// are also unreserved or of the other category.
    fn identifier_allowed(&self, suggestion_type: SuggestionState, text: &str) -> bool {
        let categories = self.keywords.categories(text);
        let banned_category = banned_category(suggestion_type);
        if suggestion_type == SuggestionState::TypeName {
            return !categories.contains(PegKeywordCategory::Reserved)
                && !categories.contains(banned_category);
        }
        let allowed_override_category = if banned_category == PegKeywordCategory::ColName {
            PegKeywordCategory::TypeFunc
        } else {
            PegKeywordCategory::ColName
        };
        let has_banned_flag =
            categories.contains(PegKeywordCategory::Reserved) || categories.contains(banned_category);
        let has_allowed_flag = categories.contains(PegKeywordCategory::Unreserved)
            || categories.contains(allowed_override_category);
        !has_banned_flag || has_allowed_flag
    }

    /// `Matcher::AddSuggestion`: adds the matcher's suggestions unless it already added
    /// them through this state (grammars are recursive).
    fn add_suggestion(
        &self,
        id: MatcherId,
        ctx: &mut MatchContext<'_>,
        state: &mut MatchState,
    ) -> SuggestionType {
        if !state.added_suggestions.insert(id) {
            return SuggestionType::Mandatory;
        }
        self.add_suggestion_internal(id, ctx, state)
    }

    /// `Matcher::AddSuggestionInternal`.
    fn add_suggestion_internal(
        &self,
        id: MatcherId,
        ctx: &mut MatchContext<'_>,
        state: &mut MatchState,
    ) -> SuggestionType {
        match &self.matcher(id).kind {
            MatcherKind::Keyword {
                keyword,
                score_bonus,
                extra_char,
            } => {
                let mut candidate = AutoCompleteCandidate::new(
                    keyword.clone(),
                    SuggestionState::Keyword,
                    *score_bonus,
                    CandidateType::Keyword,
                );
                candidate.extra_char = *extra_char;
                ctx.suggestions.push(MatcherSuggestion::Keyword(candidate));
                SuggestionType::Mandatory
            }
            MatcherKind::List(children) => {
                for child in children {
                    if self.add_suggestion(*child, ctx, state) == SuggestionType::Mandatory {
                        // This one must match before the rest.
                        return SuggestionType::Mandatory;
                    }
                }
                // Every child was optional: so is the list.
                SuggestionType::Optional
            }
            MatcherKind::Optional(child) => {
                self.add_suggestion(*child, ctx, state);
                SuggestionType::Optional
            }
            MatcherKind::Choice(children) => {
                for child in children {
                    self.add_suggestion(*child, ctx, state);
                }
                SuggestionType::Mandatory
            }
            MatcherKind::Repeat(element) => {
                self.add_suggestion(*element, ctx, state);
                SuggestionType::Mandatory
            }
            MatcherKind::Identifier { suggestion_type, .. } => {
                ctx.suggestions.push(MatcherSuggestion::Entries(*suggestion_type));
                SuggestionType::Mandatory
            }
            MatcherKind::StringLiteral | MatcherKind::NumberLiteral | MatcherKind::Operator => {
                SuggestionType::Mandatory
            }
        }
    }

    /// Matches the tokens of `ctx` against the root rule and builds their parse tree
    /// (`Matcher::MatchParseResult` on `RootMatcher`); `None` if they do not match.
    pub fn match_root_parse_result(
        &'static self,
        ctx: &mut MatchContext<'_>,
        state: &mut MatchState,
    ) -> Result<Option<ParseResult>> {
        self.match_parse_result(self.root, ctx, state)
    }

    /// `Matcher::MatchParseResult`: the parse tree of the tokens the matcher matches at
    /// the state's position, which then moves past them.
    fn match_parse_result(
        &'static self,
        id: MatcherId,
        ctx: &mut MatchContext<'_>,
        state: &mut MatchState,
    ) -> Result<Option<ParseResult>> {
        let matcher = self.matcher(id);
        let name = matcher.name.as_str();
        let token = ctx.tokens.get(state.token_index);
        let start_offset = token.map(|token| token.offset);
        let leaf = |kind: ParseResultKind| Some(ParseResult::new(name, start_offset, kind));
        Ok(match &matcher.kind {
            MatcherKind::List(children) => {
                let mut list_state = state.child();
                let mut results = Vec::with_capacity(children.len());
                for child in children {
                    let Some(result) = self.match_parse_result(*child, ctx, &mut list_state)? else {
                        return Ok(None);
                    };
                    results.push(result);
                }
                state.token_index = list_state.token_index;
                leaf(ParseResultKind::List(results))
            }
            MatcherKind::Optional(child) => {
                let mut child_state = state.child();
                match self.match_parse_result(*child, ctx, &mut child_state)? {
                    // Not matching yields an empty optional.
                    None => Some(ParseResult::new("", None, ParseResultKind::Optional(None))),
                    Some(result) => {
                        state.token_index = child_state.token_index;
                        Some(ParseResult::new(
                            result.name,
                            start_offset,
                            ParseResultKind::Optional(Some(Box::new(result))),
                        ))
                    }
                }
            }
            MatcherKind::Choice(children) => {
                for (selected, child) in children.iter().enumerate() {
                    let mut choice_state = state.child();
                    if let Some(result) = self.match_parse_result(*child, ctx, &mut choice_state)? {
                        state.token_index = choice_state.token_index;
                        return Ok(Some(ParseResult::new(
                            result.name,
                            start_offset,
                            ParseResultKind::Choice {
                                result: Box::new(result),
                                selected,
                            },
                        )));
                    }
                }
                None
            }
            MatcherKind::Repeat(element) => {
                let mut repeat_state = state.child();
                // The element must match at least once.
                let Some(first) = self.match_parse_result(*element, ctx, &mut repeat_state)? else {
                    return Ok(None);
                };
                let mut results = vec![first];
                loop {
                    state.token_index = repeat_state.token_index;
                    if repeat_state.token_index >= ctx.tokens.len() {
                        break;
                    }
                    let Some(next) = self.match_parse_result(*element, ctx, &mut repeat_state)? else {
                        break;
                    };
                    results.push(next);
                }
                Some(ParseResult::new(
                    "",
                    start_offset,
                    ParseResultKind::Repeat(results),
                ))
            }
            MatcherKind::Keyword { .. }
            | MatcherKind::Identifier { .. }
            | MatcherKind::StringLiteral
            | MatcherKind::NumberLiteral
            | MatcherKind::Operator => {
                let Some(token) = token else {
                    return Ok(None);
                };
                if !self.matches(id, ctx, state)? {
                    return Ok(None);
                }
                leaf(Self::token_parse_result(
                    &matcher.kind,
                    &token.text,
                    ctx.preserve_identifier_case,
                ))
            }
        })
    }

    /// The parse result of a single matched token (the `MatchParseResult` of the token
    /// matchers).
    fn token_parse_result(kind: &MatcherKind, text: &str, preserve_identifier_case: bool) -> ParseResultKind {
        match kind {
            MatcherKind::Keyword { .. } => ParseResultKind::Keyword(text.to_owned()),
            MatcherKind::Identifier {
                suggestion_type,
                reserved,
            } => {
                let mut result = if is_quoted_with(text, b'"') {
                    unquote(text).replace("\"\"", "\"")
                } else if preserve_identifier_case {
                    text.to_owned()
                } else {
                    text.to_ascii_lowercase()
                };
                // Table and file names may be strings (not for reserved identifiers).
                if !reserved && is_quoted_with(&result, b'\'') && supports_string_literal(*suggestion_type) {
                    result = unquote(&result).replace("''", "'");
                }
                ParseResultKind::Identifier(result)
            }
            MatcherKind::StringLiteral => {
                let (string_type, prefix_len) = special_string_info(text);
                ParseResultKind::String {
                    text: text
                        .get(prefix_len..text.len() - 1)
                        .unwrap_or_default()
                        .replace("''", "'"),
                    string_type,
                }
            }
            MatcherKind::NumberLiteral => ParseResultKind::Number(text.to_owned()),
            _ => ParseResultKind::Operator(text.to_owned()),
        }
    }

    /// `Matcher::ToString` of the matcher.
    #[cfg(test)]
    fn describe(&self, id: MatcherId) -> String {
        let name = |child: &MatcherId| {
            let matcher = self.matcher(*child);
            if matcher.name.is_empty() {
                self.describe(*child)
            } else {
                matcher.name.clone()
            }
        };
        match &self.matcher(id).kind {
            MatcherKind::Keyword { keyword, .. } => format!("'{keyword}'"),
            MatcherKind::List(children) => {
                format!("({})", children.iter().map(name).collect::<Vec<_>>().join(" "))
            }
            MatcherKind::Optional(child) => format!("{}?", name(child)),
            MatcherKind::Choice(children) => children.iter().map(name).collect::<Vec<_>>().join(" / "),
            MatcherKind::Repeat(child) => format!("{}*", name(child)),
            MatcherKind::Identifier { suggestion_type, .. } => format!("{suggestion_type:?}"),
            MatcherKind::StringLiteral => "STRING_LITERAL".to_owned(),
            MatcherKind::NumberLiteral => "NUMBER_LITERAL".to_owned(),
            MatcherKind::Operator => "OPERATOR".to_owned(),
        }
    }
}

/// `IdentifierMatcher::GetBannedCategory`.
fn banned_category(suggestion_type: SuggestionState) -> PegKeywordCategory {
    match suggestion_type {
        SuggestionState::ScalarFunctionName | SuggestionState::TableFunctionName => {
            PegKeywordCategory::ColName
        }
        _ => PegKeywordCategory::TypeFunc,
    }
}

/// `IdentifierMatcher::SupportsStringLiteral`: table and file names may be strings.
const fn supports_string_literal(suggestion_type: SuggestionState) -> bool {
    matches!(
        suggestion_type,
        SuggestionState::TableName | SuggestionState::FileName
    )
}

/// `IdentifierMatcher::IsQuoted` / `IsSingleQuoted`: whether the text starts and ends
/// with `quote`.
fn is_quoted_with(text: &str, quote: u8) -> bool {
    let bytes = text.as_bytes();
    bytes.first() == Some(&quote) && bytes.last() == Some(&quote)
}

/// `text` without its first and last character (DuckDB's `substr(1, size - 2)`, empty
/// for a lone quote).
fn unquote(text: &str) -> &str {
    text.get(1..text.len().saturating_sub(1)).unwrap_or_default()
}

/// `IdentifierMatcher::IsIdentifier`: a quoted identifier, a string where the kind of
/// name allows one, or a word.
fn is_identifier(suggestion_type: SuggestionState, text: &str) -> bool {
    let Some(&first) = text.as_bytes().first() else {
        return false;
    };
    if is_quoted_with(text, b'\'') && supports_string_literal(suggestion_type) {
        return true;
    }
    is_quoted_with(text, b'"') || is_keyword_character(first)
}

/// `StringLiteralMatcher::MatchStringLiteral`.
fn is_string_literal(text: &str) -> bool {
    let (_, prefix_len) = special_string_info(text);
    let bytes = text.as_bytes();
    // DuckDB reads `text[prefix_len - 1]`; an empty token never reaches here.
    prefix_len > 0
        && bytes.len() > prefix_len
        && bytes[prefix_len - 1] == b'\''
        && bytes.last() == Some(&b'\'')
}

/// `NumberLiteralMatcher::MatchNumberLiteral`.
fn is_number_literal(text: &str) -> Result<bool> {
    let bytes = text.as_bytes();
    let Some(&first) = bytes.first() else {
        return Ok(false);
    };
    // A lone '.' is a dot operator, not a number ('?.method()').
    if !is_initial_number(first) || bytes == b"." {
        return Ok(false);
    }
    let mut scientific_notation = false;
    for &c in &bytes[1..] {
        if is_scientific(c) {
            if scientific_notation {
                return Err(Error::parser("Already found scientific notation"));
            }
            scientific_notation = true;
        }
        if scientific_notation && (c == b'+' || c == b'-') {
            continue;
        }
        if !is_number(c) {
            return Ok(false);
        }
    }
    Ok(true)
}

/// `OperatorMatcher::MatchOperator`: operators of two or more characters that no other
/// rule handles.
fn is_operator(text: &str) -> bool {
    // The lambda and JSON arrows, single characters (handled at their precedence),
    // comparisons and LIKE-style operators have rules of their own.
    const EXCLUDED: [&str; 13] = [
        "->", "->>", "<=", ">=", "!=", "==", "<>", "~~", "~~*", "~~~", "!~~", "!~~*", "!~",
    ];
    text.len() > 1 && !EXCLUDED.contains(&text) && text.bytes().all(is_operator_char)
}

/// An entry of `MatcherFactory`'s bracket stack (DuckDB's `MatcherListEntry`): a list
/// being filled, or a choice receiving its next alternative; for a call of a
/// parameterized rule, the rule's name.
#[derive(Clone, Copy, Debug)]
struct MatcherListEntry<'g> {
    matcher: MatcherId,
    function_name: Option<&'g str>,
}

/// Builds matchers from grammar rules (DuckDB's `MatcherFactory`).
struct MatcherFactory<'p, 'g> {
    parser: &'p PegParser<'g>,
    matchers: Vec<Matcher>,
    /// The matchers created per rule, and the overridden rules (`matchers`).
    rule_matchers: HashMap<String, MatcherId>,
    /// Keywords with their own score or extra character, by lower-case keyword
    /// (`keyword_overrides`).
    keyword_overrides: HashMap<String, MatcherId>,
}

impl<'p, 'g> MatcherFactory<'p, 'g> {
    fn new(parser: &'p PegParser<'g>) -> Self {
        Self {
            parser,
            matchers: Vec::new(),
            rule_matchers: HashMap::new(),
            keyword_overrides: HashMap::new(),
        }
    }

    /// `MatcherAllocator::Allocate`.
    fn allocate(&mut self, kind: MatcherKind) -> MatcherId {
        let id = MatcherId(u32::try_from(self.matchers.len()).unwrap_or(u32::MAX));
        self.matchers.push(Matcher {
            kind,
            name: String::new(),
        });
        id
    }

    /// `MatcherFactory::Keyword`: the overriding matcher of `keyword`, or a new one.
    fn keyword(&mut self, keyword: &str) -> MatcherId {
        if let Some(id) = self.keyword_overrides.get(&keyword.to_ascii_lowercase()) {
            return *id;
        }
        self.allocate(MatcherKind::Keyword {
            keyword: keyword.to_owned(),
            score_bonus: 0,
            extra_char: Some(' '),
        })
    }

    fn list(&mut self, children: Vec<MatcherId>) -> MatcherId {
        self.allocate(MatcherKind::List(children))
    }

    /// `MatcherFactory::AddKeywordOverride`.
    fn add_keyword_override(&mut self, keyword: &str, score_bonus: i32, extra_char: Option<char>) {
        let id = self.allocate(MatcherKind::Keyword {
            keyword: keyword.to_owned(),
            score_bonus,
            extra_char,
        });
        self.keyword_overrides
            .entry(keyword.to_ascii_lowercase())
            .or_insert(id);
    }

    /// `MatcherFactory::AddRuleOverride`.
    fn add_rule_override(&mut self, rule: &str, matcher: MatcherId) {
        self.rule_matchers.entry(rule.to_owned()).or_insert(matcher);
    }

    /// `MatcherFactory::CreateMatcher(grammar, root_rule)`: registers the overrides and
    /// creates the matchers of every rule reachable from `root_rule`.
    fn create_root(&mut self, root_rule: &'g str) -> Result<MatcherId> {
        use SuggestionState as S;
        self.add_keyword_override("TABLE", 1, Some(' '));
        self.add_keyword_override(".", 0, None);
        self.add_keyword_override("(", 0, None);
        let overrides: [(&str, MatcherKind); 21] = [
            ("Identifier", identifier(S::Variable, false)),
            ("ReservedIdentifier", identifier(S::Variable, true)),
            ("CatalogName", identifier(S::CatalogName, false)),
            ("SchemaName", identifier(S::SchemaName, false)),
            ("ReservedSchemaName", identifier(S::SchemaName, true)),
            ("TableName", identifier(S::TableName, false)),
            ("ReservedTableName", identifier(S::TableName, true)),
            ("ColumnName", identifier(S::ColumnName, false)),
            ("ReservedColumnName", identifier(S::ColumnName, true)),
            ("IndexName", identifier(S::Variable, false)),
            ("SequenceName", identifier(S::Variable, false)),
            ("FunctionName", identifier(S::ScalarFunctionName, false)),
            ("ReservedFunctionName", identifier(S::ScalarFunctionName, true)),
            ("TableFunctionName", identifier(S::TableFunctionName, false)),
            ("TypeName", identifier(S::TypeName, false)),
            ("PragmaName", identifier(S::PragmaName, false)),
            ("SettingName", identifier(S::SettingName, false)),
            ("CopyOptionName", identifier(S::Variable, true)),
            ("NumberLiteral", MatcherKind::NumberLiteral),
            ("StringLiteral", MatcherKind::StringLiteral),
            ("OperatorLiteral", MatcherKind::Operator),
        ];
        for (rule, kind) in overrides {
            // The literal matchers name themselves (their constructors set `name`).
            let name = match kind {
                MatcherKind::NumberLiteral => "NumberLiteral",
                MatcherKind::StringLiteral => "StringLiteral",
                _ => "",
            };
            let id = self.allocate(kind);
            name.clone_into(&mut self.matchers[id.0 as usize].name);
            self.add_rule_override(rule, id);
        }
        self.create_matcher(root_rule, None)
    }

    /// `MatcherFactory::CreateMatcher(parser, rule_name, parameters)`: the matcher of a
    /// rule, or of a call of a parameterized rule with `parameter`. Rule matchers are
    /// cached before their contents are built, since rules are recursive.
    fn create_matcher(&mut self, rule_name: &'g str, parameter: Option<MatcherId>) -> Result<MatcherId> {
        let is_function_call = parameter.is_some();
        if !is_function_call && let Some(id) = self.rule_matchers.get(rule_name) {
            return Ok(*id);
        }
        let parser = self.parser;
        let rule = parser.rule(rule_name).ok_or_else(|| {
            Error::internal(format!(
                "Failed to create matcher for rule {rule_name} - rule is missing"
            ))
        })?;
        let matcher = self.list(Vec::new());
        if !is_function_call {
            self.rule_matchers.insert(rule_name.to_owned(), matcher);
        }
        if rule.parameters.len() > 1 {
            return Err(Error::internal(
                "Only functions with a single parameter are supported",
            ));
        }
        if rule.parameters.len() != usize::from(is_function_call) {
            return Err(Error::internal(format!(
                "Parameter count mismatch (rule {rule_name} expected {} parameters but got {})",
                rule.parameters.len(),
                usize::from(is_function_call)
            )));
        }
        let mut stack = vec![MatcherListEntry {
            matcher,
            function_name: None,
        }];
        for token in &rule.tokens {
            match token.ty {
                PegTokenType::Literal => {
                    let keyword = self.keyword(token.text);
                    self.add_to_stack(&mut stack, keyword)?;
                }
                PegTokenType::Reference => {
                    let child = match (rule.parameter_index(token.text), parameter) {
                        // A reference to the parameter: the argument itself.
                        (Some(_), Some(argument)) => argument,
                        _ => self.create_matcher(token.text, None)?,
                    };
                    self.add_to_stack(&mut stack, child)?;
                }
                PegTokenType::FunctionCall => {
                    // `MatcherList::BeginFunction`: collect the arguments in a list.
                    let arguments = self.list(Vec::new());
                    stack.push(MatcherListEntry {
                        matcher: arguments,
                        function_name: Some(token.text),
                    });
                }
                PegTokenType::Operator => self.apply_operator(&mut stack, token.text, rule_name)?,
                PegTokenType::Regex => {
                    return Err(Error::internal(format!(
                        "REGEX operator not supported in PEG grammar (found in rule {rule_name})"
                    )));
                }
            }
        }
        if stack.len() != 1 {
            return Err(Error::internal(
                "PEG matcher create error - unclosed bracket found",
            ));
        }
        rule_name.clone_into(&mut self.matchers[matcher.0 as usize].name);
        Ok(matcher)
    }

    /// The children of the list matcher `id`.
    fn list_children(&mut self, id: MatcherId) -> Result<&mut Vec<MatcherId>> {
        match &mut self.matchers[id.0 as usize].kind {
            MatcherKind::List(children) => Ok(children),
            _ => Err(Error::internal("expected a list matcher")),
        }
    }

    /// `MatcherList::AddMatcher`: appends to the list on top of the stack, or adds the
    /// next alternative of the choice on top (and pops it).
    fn add_to_stack(&mut self, stack: &mut Vec<MatcherListEntry<'g>>, matcher: MatcherId) -> Result<()> {
        let root = stack
            .last()
            .ok_or_else(|| Error::internal("PEG matcher create error - empty matcher stack"))?
            .matcher;
        match &mut self.matchers[root.0 as usize].kind {
            MatcherKind::List(children) => children.push(matcher),
            MatcherKind::Choice(children) => {
                if stack.len() <= 1 {
                    return Err(Error::internal(
                        "Choice matcher should never be the root in the matcher stack",
                    ));
                }
                children.push(matcher);
                stack.pop();
            }
            _ => return Err(Error::internal("Cannot add matcher to root matcher of this type")),
        }
        Ok(())
    }

    /// The handling of an operator token in `CreateMatcher`.
    fn apply_operator(
        &mut self,
        stack: &mut Vec<MatcherListEntry<'g>>,
        op: &str,
        rule_name: &str,
    ) -> Result<()> {
        let last_root = stack
            .last()
            .ok_or_else(|| Error::internal("PEG matcher create error - empty matcher stack"))?
            .matcher;
        match op {
            "?" | "*" | "+" => {
                // Wraps the last matcher: `?` in an optional, `+` in a repeat, `*` in an
                // optional repeat.
                let last = self
                    .list_children(last_root)
                    .map_err(|_| Error::internal("Optional/Repeat expected a list matcher"))?
                    .pop()
                    .ok_or_else(|| Error::internal("Optional/Repeat rule found as first token"))?;
                let repeated = if op == "?" {
                    last
                } else {
                    self.allocate(MatcherKind::Repeat(last))
                };
                let wrapped = if op == "+" {
                    repeated
                } else {
                    self.allocate(MatcherKind::Optional(repeated))
                };
                self.list_children(last_root)?.push(wrapped);
            }
            "/" => {
                // A choice between the last matcher and the next one.
                let previous = *self
                    .list_children(last_root)
                    .map_err(|_| Error::internal("OR expected a list matcher"))?
                    .last()
                    .ok_or_else(|| Error::internal("OR rule found as first token"))?;
                if matches!(self.matchers[previous.0 as usize].kind, MatcherKind::Choice(_)) {
                    stack.push(MatcherListEntry {
                        matcher: previous,
                        function_name: None,
                    });
                } else {
                    let choice = self.allocate(MatcherKind::Choice(vec![previous]));
                    let children = self.list_children(last_root)?;
                    children.pop();
                    children.push(choice);
                    stack.push(MatcherListEntry {
                        matcher: choice,
                        function_name: None,
                    });
                }
            }
            "(" => {
                let bracket = self.list(Vec::new());
                stack.push(MatcherListEntry {
                    matcher: bracket,
                    function_name: None,
                });
            }
            ")" => self.close_bracket(stack)?,
            // DuckDB ignores NOT operators.
            "!" => {}
            _ => {
                return Err(Error::internal(format!(
                    "unrecognized peg operator type in rule {rule_name}"
                )));
            }
        }
        Ok(())
    }

    /// `MatcherList::CloseBracket`: a bracketed list joins the matcher below it; the
    /// arguments of a rule call become the parameter of the called rule's matcher.
    fn close_bracket(&mut self, stack: &mut Vec<MatcherListEntry<'g>>) -> Result<()> {
        if stack.len() <= 1 {
            return Err(Error::internal(
                "PEG matcher create error - found too many close brackets",
            ));
        }
        let Some(entry) = stack.pop() else {
            return Ok(());
        };
        let matcher = match entry.function_name {
            None => entry.matcher,
            Some(function_name) => {
                let arguments = self.list_children(entry.matcher)?.clone();
                // More than one argument is wrapped in a list.
                let parameter = match arguments.as_slice() {
                    [single] => *single,
                    _ => self.list(arguments),
                };
                self.create_matcher(function_name, Some(parameter))?
            }
        };
        self.add_to_stack(stack, matcher)
    }
}

/// The identifier kind of a rule override.
const fn identifier(suggestion_type: SuggestionState, reserved: bool) -> MatcherKind {
    MatcherKind::Identifier {
        suggestion_type,
        reserved,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tokens(texts: &[&str]) -> Vec<MatcherToken> {
        texts.iter().map(|text| MatcherToken::new(*text, 0)).collect()
    }

    #[test]
    fn the_inlined_grammar_compiles() {
        let grammar = Grammar::get().unwrap();
        assert_eq!(grammar.matcher(grammar.root).name, "Statement");
        assert!(grammar.describe(grammar.root).contains("SelectStatement"));
    }

    #[test]
    fn complete_statements_match() {
        let grammar = Grammar::get().unwrap();
        for sql in [
            ["SELECT", "1"].as_slice(),
            &["SELECT", "*", "FROM", "t", "WHERE", "a", "=", "1"],
            &["CREATE", "TABLE", "t", "(", "i", "INTEGER", ")"],
        ] {
            let tokens = tokens(sql);
            let mut ctx = MatchContext::new(&tokens);
            let mut state = MatchState::default();
            assert!(grammar.match_root(&mut ctx, &mut state).unwrap(), "{sql:?}");
            assert_eq!(state.token_index, tokens.len(), "{sql:?}");
        }
    }

    #[test]
    fn exhausted_tokens_suggest_keywords() {
        let grammar = Grammar::get().unwrap();
        let tokens = tokens(&["SELECT", "*"]);
        let mut ctx = MatchContext::new(&tokens);
        grammar.match_root(&mut ctx, &mut MatchState::default()).unwrap();
        let keywords: Vec<&[u8]> = ctx
            .suggestions
            .iter()
            .filter_map(|suggestion| match suggestion {
                MatcherSuggestion::Keyword(candidate) => Some(candidate.candidate.as_bytes()),
                MatcherSuggestion::Entries(_) => None,
            })
            .collect();
        assert!(keywords.contains(&b"FROM".as_slice()), "{keywords:?}");
    }

    #[test]
    fn number_literals() {
        assert!(is_number_literal("1e-5").unwrap());
        assert!(is_number_literal(".5").unwrap());
        assert!(!is_number_literal(".").unwrap());
        assert!(!is_number_literal("1a").unwrap());
        assert!(is_number_literal("1e5e3").is_err());
    }

    #[test]
    fn string_literals() {
        assert!(is_string_literal("'a'"));
        assert!(is_string_literal("E'a'"));
        assert!(!is_string_literal("'"));
        assert!(!is_string_literal("x"));
        assert_eq!(
            special_string_info("X'ab'"),
            (SpecialStringCharacter::HexadecimalString, 2)
        );
    }
}
