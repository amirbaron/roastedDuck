#[test]
fn nested_and_variant_hashes_match_cpp_constants_stored_rows_and_selections() -> Result<()> {
    let mut c = Database::open_in_memory()?.connect()?;
    let mut differences = Vec::new();
    for &(expression, hash, combined) in CASES {
        let expected = [Value::ubigint(hash), Value::ubigint(combined)];
        let r = c.query(format!("SELECT hash(v),hash(17,v) FROM (SELECT {expression} v)"))?;
        for (column, value) in expected.iter().enumerate() {
            if r.value(column, 0) != *value {
                differences.push(format!(
                    "constant {expression} column {column}: {:?} expected {value:?}",
                    r.value(column, 0)
                ));
            }
        }
        c.query(format!(
            "CREATE OR REPLACE TABLE hash_probe AS SELECT i,{expression} v FROM range(3)t(i)"
        ))?;
        let r = c.query("SELECT hash(v),hash(17,v) FROM hash_probe ORDER BY i")?;
        for row in 0..3 {
            for (column, value) in expected.iter().enumerate() {
                if r.value(column, row) != *value {
                    differences.push(format!(
                        "stored {expression} row {row} column {column}: {:?} expected {value:?}",
                        r.value(column, row)
                    ));
                }
            }
        }
        let r = c.query("SELECT hash(v),hash(17,v) FROM hash_probe WHERE i IN(0,2) ORDER BY i")?;
        for row in 0..2 {
            for (column, value) in expected.iter().enumerate() {
                if r.value(column, row) != *value {
                    differences.push(format!(
                        "selected {expression} row {row} column {column}: {:?} expected {value:?}",
                        r.value(column, row)
                    ));
                }
            }
        }
    }
    assert!(differences.is_empty(), "{}", differences.join("\n"));
    Ok(())
}
